"""Generate the authentic finite valid-CMOS startup/DI blocks; no runtime decoder."""
from pathlib import Path
import argparse
import hashlib
import json
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_video_irq as shared

ROOT=shared.ROOT
MANIFEST=Path(__file__).with_name('valid_cmos_startup_path.json')
OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_valid_cmos_startup.inc'  # generated by the setup


def generate(rom,manifest=None):
    manifest=json.loads(MANIFEST.read_text())if manifest is None else manifest
    if manifest.get('program_sha256')!=shared.PROGRAM_SHA256:
        raise ValueError('Valid-CMOS startup program identity differs')
    pcs=tuple(int(pc,16)for pc in manifest['pcs'])
    if not pcs or pcs!=tuple(sorted(set(pcs))):raise ValueError('Valid-CMOS startup PCs must be unique and sorted')
    # Instruction word counts only; the words are read from the user's program ROM and checked by SHA-256
    # (8-byte little-endian words, PC order: tools/mk2/oracle_digest.py serialization).
    counts={int(pc,16):count for pc,count in manifest['word_counts'].items()}
    if set(counts)!=set(pcs):raise ValueError('Valid-CMOS startup opcode coverage differs')
    words=[]
    for pc in pcs:
        offset=(pc-0xff800000)//8
        if pc&15 or pc<0xff800000 or counts[pc]<1 or offset+counts[pc]*2>len(rom):
            raise ValueError('Valid-CMOS startup opcode differs at '+hex(pc))
        words+=[int.from_bytes(rom[offset+2*n:offset+2*n+2],'little') for n in range(counts[pc])]
    if hashlib.sha256(b''.join(value.to_bytes(8,'little') for value in words)).hexdigest()!=manifest['words_sha256']:
        raise ValueError('Valid-CMOS startup opcode differs from the authenticated program words')
    successors={int(pc,16):tuple(int(value,16)for value in values)for pc,values in manifest['successors'].items()}
    if set(successors)!=set(pcs)or any(value not in set(pcs)|{0xff811710}for values in successors.values()for value in values):
        raise ValueError('Valid-CMOS startup successor outside the observed static path')
    shared.generate(rom,pcs=pcs,successors=successors,end=0xff811710,
                    generator='tools/mk2/generate_valid_cmos_startup.py')
    from tools.mk2.generate_architectural import generate as architectural
    return {path.name: text for path, text in architectural(rom)[0].items()}[OUTPUT.name]


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom-directory',type=Path,default=ROOT/'roms/mk2')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();source=generate(shared.load_program(args.rom_directory))
    if args.check:
        if OUTPUT.read_text()!=source:raise ValueError('Valid-CMOS startup generated source is stale')
    else:OUTPUT.write_text(source,encoding='utf-8',newline='\n')
    print('Valid-CMOS startup: '+str(source.count('case 0x'))+' authenticated static blocks')


if __name__=='__main__':main()
