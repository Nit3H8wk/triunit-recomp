"""Fixed L3.1 pre-Start waiting blocks, measured before the legal Start request."""
from pathlib import Path
import json
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_next_wait as pair
from tools.mk2 import generate_video_irq as shared

START, END_PC, END = 6087360, 0xff80dd30, 22081952
OUTPUT = __import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_prestart_wait.inc'  # generated by the setup
PATH = Path(__file__).with_name('prestart_wait_path.json')
measured = json.loads(PATH.read_text(encoding='utf8'))
WINDOWS=tuple(measured['windows'])
if len(WINDOWS)!=16: raise ValueError('Pre-Start scope requires sixteen measured intervals')
BOUNDS_OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_prestart_wait_bounds.inc'  # generated by the setup


def interval(index):
    if type(index) is not int or not 0<=index<len(WINDOWS):
        raise ValueError('Pre-Start interval index must be an integer from0 through15')
    return WINDOWS[index]


def generate_bounds():
    rows=['// Generated expected-only CPU boundaries; never imported into native state.']
    for w in WINDOWS:
        rows.append('{'+str(w['end'])+'ull,'+str(w['cpu_rows'])+'ull,"'+w['end_cpu34_sha256']+'"},')
    return '\n'.join(rows)+'\n'

PCS = tuple(sorted(set(pair.PCS) | {int(pc, 16) for pc in measured['new_pcs']}))
SUCCESSORS = dict(pair.SUCCESSORS)
for source, targets in measured['successors'].items():
    pc = int(source, 16)
    SUCCESSORS[pc] = tuple(sorted(set(SUCCESSORS.get(pc, ())) | {int(p, 16) for p in targets}))


def generate(rom):
    pair.generate(rom)  # Authenticate the unchanged fallback translation and decoder first.
    from tools.mk2.offline_decode import decode
    rows, _ = decode(rom, PCS)
    qualified, previous = set(PCS), set(pair.PCS)
    output = ['// Generated offline by tools/mk2/generate_prestart_wait.py; do not hand edit.',
              '// Authenticated L3.1 ROM SHA256: ' + shared.PROGRAM_SHA256,
              '// Only changed/new blocks; all other PCs retain the next-wait fixed translation.']
    for pc in PCS:
        size, flags, raw, asm = rows[pc]
        code = shared.emit_instruction(pc,size,asm,raw,qualified,SUCCESSORS,end=END_PC)
        if pc in previous and code == shared.emit_instruction(
                pc,size,asm,raw,previous,pair.SUCCESSORS,end=END_PC):
            continue
        output.extend([f'case 0x{pc:08x}u: {{ // {asm}', '    '+code, '    break;', '}'])
    return '\n'.join(output)+'\n'


if __name__ == '__main__':
    OUTPUT.write_text(generate(shared.load_program(shared.ROOT / 'roms/mk2')), encoding='utf8')
    BOUNDS_OUTPUT.write_text(generate_bounds(),encoding='utf8')
