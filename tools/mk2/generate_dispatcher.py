def generate(rom):
    from tools.mk2 import offline_decode,generate_static_cfg
    rows,proof=offline_decode.decode(rom,PCS)
    vector=int.from_bytes(rom[0xffff8:0xffffc],'little')
    class RomAddresses:
        def __contains__(self,pc):return 0xff800000<=pc<=0xfffffff0 and not pc&15
    output=['// Generated offline by tools/mk2/generate_architectural.py; no runtime decoder.',
            '// ROM SHA256 '+shared.PROGRAM_SHA256]
    for pc,(size,flags,raw,asm)in sorted(rows.items()):
        edges={pc:generate_static_cfg.direct_targets(pc,size,asm,vector)or()}
        code=shared.emit_instruction(pc,size,asm,raw,RomAddresses(),edges,end=END)
        output.append(f'case 0x{pc:08x}u: {{ // {asm}\n    {code}\n    break;\n}}')
    return '\n'.join(output)+'\n'

