def register(value):
    if value in ("SP", "A15", "B15"):
        return "s.a[15]"
    if not re.fullmatch(r"[AB](?:[0-9]|1[0-5])", value):
        raise ValueError("Unsupported register: " + value)
    return f"s.{'a' if value[0] == 'A' else 'b'}[{int(value[1:])}]"


def immediate(value):
    if not re.fullmatch(r"[0-9A-F]+h", value):
        raise ValueError("Unsupported immediate: " + value)
    return int(value[:-1], 16)


def transfer_target(op, operand):
    target = immediate(operand)
    return target & 0xfffffff0 if op == 'CALLA' or op.startswith('JA') else target


def constant(value):
    return f"0x{value & 0xffffffff:08x}u"


def memory(value, field):
    """Return address and ordered pre/post actions, without reading memory."""
    if value.startswith("@"):
        return constant(immediate(value[1:])), "", "", "absolute"
    match = re.fullmatch(r"(-?)\*([AB]\d+|SP)(?:\(([0-9A-F]+h)\))?(\+?)", value)
    if not match:
        raise ValueError("Unsupported memory operand: " + value)
    pre, name, offset, post = match.groups()
    reg = register(name)
    if pre and post:
        raise ValueError("Conflicting memory updates")
    if offset and (pre or post):
        raise ValueError("Offset/update memory form is not qualified")
    address = reg
    if offset:
        signed = immediate(offset)
        if signed & 0x8000:
            signed |= 0xffff0000
        address = f"({reg}+{constant(signed)})"
    return (address, f"{reg} -= o.FieldWidth({field}); " if pre else "",
            f"{reg} += o.FieldWidth({field}); " if post else "",
            "offset" if offset else "pre" if pre else "post" if post else "indirect")


_OPCODE_TABLE = None


def reserved(word):
    """Pinned 34010tbl.hxx dispatches word>>4; an unimpl entry is a 16-bit, 1-cycle no-op in 34010ops.hxx even where
    the pinned disassembler masks the low operand bits and prints a mnemonic (e.g. 033Fh as CLRC, 0D20h as CALLR)."""
    global _OPCODE_TABLE
    if _OPCODE_TABLE is None:
        directory = ROOT / "docs/investigation/decoder-research"
        import json
        pinned = {s["file"]: s["sha256"] for s in json.loads((directory / "sources.json").read_text(encoding="utf8"))["sources"]}
        table = directory / "upstream/34010tbl.hxx"
        if quality.sha(table) != pinned["34010tbl.hxx"]:
            raise ValueError("Pinned TMS34010 opcode table changed")
        names = re.findall(r"&tms34010_device::(\w+)", table.read_text(encoding="utf8"))[:4096]
        if len(names) != 4096:
            raise ValueError("TMS34010 opcode table size")
        _OPCODE_TABLE = names
    return _OPCODE_TABLE[word >> 4] == "unimpl"


def emit_instruction(pc, size, asm, words, pcs, successors, *, end=END, batch_forms=False, unverified=None,
                     mame_table=False):
    """Emit static ISA semantics; calculated PCs return to the closed dispatcher.

    mame_table: words are the authentic ROM words; a reserved (unimpl) dispatch is emitted as MAME executes it.

    unverified(target): C++ statement prefix for a conditional/DSJ branch to a target outside pcs, emitted
    before the branch's effects; None (or a None result) keeps the explicit rejection."""
    if size not in (16, 32, 48, 80) or len(words) * 16 != size:
        raise ValueError("Unsupported instruction size")
    op, *tail = asm.split(None, 1)
    args = tail[0].split(",") if tail else []
    a = args[0] if args else ""
    b = args[1] if len(args) > 1 else ""
    next_pc = pc + size
    nxt = constant(next_pc)

    def finish(target=next_pc, cost=1):
        if target not in pcs and target != end:
            raise ValueError(f"Unqualified fallthrough at {pc:08x}: {target:08x}")
        return f"o.Finish({constant(target)},{cost});"

    def branch(target, cost, prefix=""):
        if target not in pcs and target != end:
            check = unverified(target) if unverified else None
            if check is None:
                return 'throw std::runtime_error("MK2 video IRQ unobserved branch");'
            return check + prefix + f"o.Finish({constant(target)},{cost});"
        return prefix + finish(target, cost)

    if mame_table and reserved(words[0]):
        if op == "DW":
            raise ValueError(f"Unsupported {pc:08x}: {asm}")
        return finish(pc + 16, 1)
    if op in ("CALLR", "CALLA", "JA"):
        target = transfer_target(op, a)
        if target not in pcs:
            raise ValueError(f"Unqualified call/jump at {pc:08x}")
        return (finish(target, 3) if op == "JA" else
                f"o.Call({constant(target)},{nxt},{3 if op == 'CALLR' else 4});")
    if op == "RETS":
        return f"o.ReturnSubroutine({immediate(a) if a else 0});"
    if op == "RETI":
        return "o.ReturnInterrupt();"
    if op == "TRAP":
        targets = successors.get(pc, ())
        if a != "1h" or len(targets) != 1 or targets[0] not in pcs:
            raise ValueError("Unqualified software trap")
        return f"o.TrapOne({constant(targets[0])},{nxt});"
    if op == "NOP":
        return finish()
    if op == "REV" and batch_forms:
        return f"{register(a)}=8; " + finish()
    if op == "GETPC":
        return f"{register(a)}={nxt}; " + finish()
    # Bitmap-text PIXBLT B,XY: shared restartable hardware semantic (mk2_pixblt.hpp), in every unit and the closure.
    if op == "PIXBLT" and pc == 0xffa592b0 and words == (0x0fa0,):
        return "o.DrawBitmapText();"
    if op == "CVXYL" and batch_forms and size == 16:
        return f"o.ConvertXY({register(a)},{register(b)},{nxt});"
    if op == "DRAV" and batch_forms and size == 16:
        return f"o.DrawAdvance({register(b)},{register(a)},{nxt});"
    if op == "PIXT":
        if batch_forms and size == 16 and len(args) == 3 and args[2] == "XY" and b.startswith("*"):
            return f"o.WriteXYPixel({register(b[1:])},{register(a)},{nxt});"
        if args != ["*B2", "B2"] or size != 16:
            raise ValueError("Unqualified pixel read")
        return f"o.PixelRead(s.b[2],s.b[2],{nxt});"
    if op == "FILL":
        if args != ["XY"] or size != 16:
            raise ValueError("Unqualified fill")
        return f"o.FillXY({nxt});"
    if op in ("JUMP", "CALL", "EXGPC"):
        target=f"({register(a)}&~uint32_t(15))"
        if op == "CALL":return f"o.Call({target},{nxt},3);"
        return f"const uint32_t target={target}; " + (f"{register(a)}={nxt}; " if op == "EXGPC" else "") + "o.Finish(target,2);"
    if op == "GETST":
        return f"{register(a)}=s.status; " + finish()
    if op == "EXGF" and batch_forms and size == 16 and b in ("0", "1"):
        return f"o.ExchangeField({register(a)},{'true' if b == '1' else 'false'},{nxt});"
    if op == "PUTST":
        return f"o.PutStatus({register(a)},{nxt});"
    if op in ("EINT", "DINT"):
        return f"o.InterruptEnable({'true' if op == 'EINT' else 'false'},{nxt});"
    if op in ("PUSHST", "POPST"):
        return f"o.{'PushStatus' if op == 'PUSHST' else 'PopStatus'}({nxt});"
    if op in ("MMTM", "MMFM"):
        allowed = ("SP",) + tuple(f'{bank}{n}' for bank in 'AB' for n in range(16))
        if a not in allowed:
            raise ValueError("Unqualified stack register")
        regs = []
        bank = None
        for item in args[1:]:
            parts = item.split("-")
            register(parts[0])
            bank = bank or (parts[0][0] if parts[0]!='SP' else 'A')
            if any(x!='SP' and x[0] != bank for x in parts):
                raise ValueError("Mixed stack banks")
            if len(parts) == 1:
                regs.append(15 if parts[0]=='SP' else int(parts[0][1:]))
            else:
                register(parts[1])
                regs.extend(range(int(parts[0][1:]), (15 if parts[1]=='SP' else int(parts[1][1:])) + 1))
        if not regs or len(set(regs)) != len(regs):
            raise ValueError("Unqualified stack alias/list")
        mask = sum(0x8000 >> n for n in regs)
        if a not in ("SP","A15","B15") and bank != a[0]:
            raise ValueError("Unqualified context base alias")
        base = "" if a in ("SP","A15","B15") else f",{int(a[1:])}"
        return f"o.{'Mmtm' if op == 'MMTM' else 'Mmfm'}(0x{mask:04x},{nxt},{'true' if bank == 'B' else 'false'}{base});"
    if op == "ABS":
        return f"o.Absolute({register(a)},{nxt});"
    if op == "DIVS":
        destination=register(b)
        if (15 if b=='SP' else int(b[1:]))%2==0:
            raise ValueError('Unqualified paired signed division')
        return f"o.DivideSignedSingle({destination},{register(a)},{nxt});"
    if op in ("MOVI", "MOVK"):
        value = immediate(a)
        if op == "MOVI":
            if size == 32 and value & 0x8000:
                value |= 0xffff0000
            return f"o.Load({register(b)},{constant(value)},{nxt},{size // 16});"
        return f"{register(b)}={constant(value)}; " + finish()
    if op == "MOVE":
        mem_a = a.startswith(("@", "*", "-*"))
        mem_b = b.startswith(("@", "*", "-*"))
        if not mem_a and not mem_b:
            return f"o.Load({register(b)},{register(a)},{nxt},1);"
        if len(args) != 3:
            # Pinned disassembler omits B here; opcode table dispatches MOVB_AR.
            if words[0] != 0x07e1 or not a.startswith("@") or mem_b or b != "A1":
                raise ValueError("Unqualified omitted field annotation")
            address = constant(immediate(a[1:]))
            return f"o.Load({register(b)},uint32_t(int32_t(int8_t(o.Read8({address})))),{nxt},5);"
        field = int(args[2])
        if field not in (0, 1):
            raise ValueError("Unqualified field")
        code = ""
        if mem_a:
            address, pre, post, kind_a = memory(a, field)
            code += pre + f"const uint32_t value=o.ReadField({address},{field}); " + post
            value = "value"
        else:
            value = register(a)
        if mem_b:
            address, pre, post, kind_b = memory(b, field)
            if mem_a:
                cost = (7 if kind_a == kind_b == "absolute" else 4 if kind_a == kind_b and kind_a in ("pre", "post")
                        else 5 if (kind_a == "offset" and kind_b in ("offset", "post")) or
                                  (kind_a == "absolute" and kind_b == "post") else 3)
            else:
                cost = {"absolute": 3, "pre": 2, "post": 1, "indirect": 1, "offset": 3}[kind_b]
            if b == "@1D01030h":
                if mem_a or field != 0:
                    raise ValueError("Unqualified host write form")
                return ('if(o.FieldWidth(0)!=16) { throw std::runtime_error("MK2 host write field"); } '
                        f"o.Record('w',0x01d01030,uint16_t({value})); o.Finish({nxt},{cost},true,uint16_t({value}));")
            code += pre + f"o.WriteField({address},{value},{field}); " + post
            return code + finish(cost=cost)
        cost = {"absolute": 5, "pre": 4, "post": 3, "indirect": 3, "offset": 5}[kind_a]
        return code + f"o.Load({register(b)},value,{nxt},{cost});"
    if op == "MOVB":
        if b.startswith(("*", "@")):
            address, pre, post, kind = memory(b, 0)
            if pre or post or kind not in ("indirect","offset","absolute"):
                raise ValueError("Unqualified byte store operand")
            if a.startswith("*"):
                source, pre, post, source_kind = memory(a,0)
                if pre or post or source_kind != "indirect" or kind != "indirect":
                    raise ValueError("Unqualified byte copy operand")
                return f"const uint32_t value=o.Read8({source}); o.WriteByte({address},value); " + finish(cost=3)
            if kind == "absolute":
                return f"o.WriteByte({address},{register(a)}); " + finish(cost=1)
            return f"o.WriteByte({address},{register(a)}); " + finish(cost=1 if kind=="indirect" else 3)
        address, pre, post, kind = memory(a, 0)
        if pre or post or kind not in ("indirect","offset"):
            raise ValueError("Unqualified byte operand")
        return f"o.Load({register(b)},uint32_t(int32_t(int8_t(o.Read8({address})))),{nxt},{3 if kind=='indirect' else 5});"
    if op == "SUBB" and batch_forms and size == 16:
        return f"o.SubtractBorrow({register(b)},{register(a)},{nxt});"
    if op == "ADDC":
        return f"o.AddCarry({register(b)},{register(a)},{nxt});"
    if op == "MOVX":
        return f"o.MoveX({register(a)},{register(b)},{nxt});"
    if op == "MOVY":
        return f"{register(b)}=({register(a)}&0xffff0000)|({register(b)}&0xffff); " + finish()
    if op == "CMPXY":
        return (f"const uint16_t x=uint16_t({register(b)})-uint16_t({register(a)}), "
                f"y=uint16_t({register(b)}>>16)-uint16_t({register(a)}>>16); "
                "s.status=(s.status&~uint32_t(0xf0000000))|(x==0?0x80000000:0)|"
                "(y&0x8000?0x40000000:0)|(y==0?0x20000000:0)|(x&0x8000?0x10000000:0); " + finish())
    if op in ("CLRC", "SETC"):
        return ("s.status&=~uint32_t(0x40000000); " if op == "CLRC" else "s.status|=0x40000000; ") + finish()
    if op == "ADDXY":
        return f"o.AddXY({register(b)},{register(a)},{nxt});"
    if op == "SUBXY":
        return f"o.SubtractXY({register(b)},{register(a)},{nxt});"
    if op == "SEXT":
        return f"o.SignExtend({register(a)},{int(b)},{nxt});"
    if op in ("SLA", "SRA"):
        # Pinned disassembler prints SRA K as 32-K (20h for K=0); 34010ops.hxx shifts by (-K)&31.
        return f"o.ShiftArithmetic({register(b)},{immediate(a) & 31},{'true' if op == 'SRA' else 'false'},{nxt});"
    if op in ("ADD", "ADDI", "ADDK", "INC", "SUB", "SUBI", "SUBK", "DEC", "CMP", "CMPI", "NEG"):
        compare = op in ("CMP", "CMPI")
        subtract = op in ("SUB", "SUBI", "SUBK", "DEC", "CMP", "CMPI", "NEG")
        dst = register(a if op in ("INC", "DEC", "NEG") else b)
        if op in ("INC", "DEC"):
            value = "1"
        elif op == "NEG":
            return f"const uint32_t value={dst}; {dst}=0; o.Arithmetic({dst},value,true,{nxt},1);"
        elif op in ("ADDI", "ADDK", "SUBI", "SUBK", "CMPI"):
            value = immediate(a)
            if size == 32 and value & 0x8000:
                value |= 0xffff0000
            value = constant(value)
        else:
            value = register(a)
        cost = size // 16
        prefix = f"uint32_t value={dst}; " if compare else ""
        return prefix + f"o.Arithmetic({'value' if compare else dst},{value},{'true' if subtract else 'false'},{nxt},{cost});"
    if op == "CLR":
        return f"o.Clear({register(a)},{nxt});"
    if op in ("AND", "ANDI", "ANDN", "OR", "ORI", "XOR", "XORI", "NOT"):
        dst = register(a if op == "NOT" else b)
        if op == "NOT":
            code = f"{dst}=~{dst}; "
        else:
            value = constant(immediate(a)) if op.endswith("I") else register(a)
            if op == "ANDN": value = "~" + value
            operator = {"AND": "&", "ANDN": "&", "OR": "|", "XOR": "^"}[op.removesuffix("I")]
            code = f"{dst}{operator}={value}; "
        return code + f"o.Zero({dst}); " + finish(cost=size // 16)
    if op == "BTST":
        value = str(immediate(a)) if a.endswith("h") else f"({register(a)}&31)"
        return f"o.Zero(({register(b)}>>{value})&1); " + finish(cost=1 if a.endswith("h") else 2)
    if op in ("SLL", "SRL", "RL"):
        # 34010ops.hxx: SRL Rs shifts by (-Rs)&31; SRL K is printed as 32-K and shifts by (-K)&31.
        if a.endswith("h"):
            count = str(immediate(a) & 31)
        else:
            count = f"((0u-{register(a)})&31)" if op == "SRL" else f"({register(a)}&31)"
        if op == "RL":
            return f"o.Rotate({register(b)},{count},{nxt});"
        return f"o.Shift({register(b)},{count},{'true' if op == 'SRL' else 'false'},{nxt});"
    if op == "SETF":
        width, sign, field = immediate(a), int(b), int(args[2])
        if width == 32:
            if size!=16 or len(words)!=1 or (words[0]&0x23f)!=((field<<9)|(sign<<5)):
                raise ValueError("Unqualified SETF")
            width=0
        if width > 31 or sign not in (0, 1) or field not in (0, 1):
            raise ValueError("Unqualified SETF")
        return f"o.SetField(0x{width | (sign << 5):x},{nxt}{',true' if field else ''});"
    if op == "ZEXT":
        if batch_forms and b == "1":
            dst = register(a)
            return ("const unsigned width=(s.status>>6)&31; "
                    f"if(width) {{ {dst}&=(uint32_t(1)<<width)-1; }} o.Zero({dst}); " + finish())
        if b != "0":
            raise ValueError("Unqualified ZEXT field")
        dst = register(a)
        return ("const unsigned width=o.FieldWidth(0); "
                f"if(width!=32) {{ {dst}&=(uint32_t(1)<<width)-1; }} o.Zero({dst}); " + finish())
    if op == "LMO":
        return f"o.LeadingOne({register(a)},{register(b)},{nxt});"
    if op == "MPYU":
        register(b)
        return f"o.MultiplyUnsigned({register(a)},{int(b[1:])},{'true' if b[0] == 'B' else 'false'},{nxt});"
    if op in ("MPYS", "DIVU"):
        register(b)
        method = "MultiplySigned" if op == "MPYS" else "DivideUnsigned"
        return f"o.{method}({register(a)},{int(b[1:])},{'true' if b[0] == 'B' else 'false'},{nxt});"
    if op in ("DSJ", "DSJS"):
        reg = register(a)
        taken, done = (3, 2) if op == "DSJ" else (2, 3)
        return (f"if({reg}!=1) {{ " + branch(immediate(b), taken, f"--{reg}; ") +
                " } else { " + branch(next_pc, done, f"--{reg}; ") + " }")
    if op in ("DSJEQ", "DSJNE") and batch_forms:
        reg = register(a)
        condition = "!=0" if op == "DSJEQ" else "==0"
        return (f"const bool decrement=(s.status&0x20000000){condition}; "
                f"if(decrement && {reg}!=1) {{ " + branch(immediate(b), 3, f"--{reg}; ") +
                " } else { " + branch(next_pc, 2, f"if(decrement) --{reg}; ") + " }")
    conditions = {"JR": "true", "JREQ": "(s.status&0x20000000)!=0", "JAEQ": "(s.status&0x20000000)!=0", "JRNE": "(s.status&0x20000000)==0",
                  "JRC": "(s.status&0x40000000)!=0", "JRNC": "(s.status&0x40000000)==0",
                  "JRN": "(s.status&0x80000000)!=0", "JRNN": "(s.status&0x80000000)==0",
                  "JRLT": "((s.status>>31)^((s.status>>28)&1))!=0",
                  "JRGE": "((s.status>>31)^((s.status>>28)&1))==0",
                  "JRLE": "(s.status&0x20000000)!=0||((s.status>>31)^((s.status>>28)&1))!=0",
                  "JRGT": "(s.status&0x20000000)==0&&((s.status>>31)^((s.status>>28)&1))==0",
                  "JRHI": "(s.status&0x60000000)==0",
                  "JRV": "(s.status&0x10000000)!=0", "JRNV": "(s.status&0x10000000)==0",
                  "JRP": "(s.status&0xa0000000)==0", "JRLS": "(s.status&0x60000000)!=0",
                  "JAC": "(s.status&0x40000000)!=0", "JANC": "(s.status&0x40000000)==0",
                  "JANE": "(s.status&0x20000000)==0", "JAN": "(s.status&0x80000000)!=0"}
    condition_op='JR'+op[2:] if op.startswith('JA') else op
    if condition_op in conditions:
        taken, done = (2, 1) if size == 16 else (3, 2) if size == 32 else (3, 4)
        return (f"if({conditions[condition_op]}) {{ " + branch(transfer_target(op, a), taken) +
                " } else { " + branch(next_pc, done) + " }")
    raise ValueError(f"Unsupported {pc:08x}: {asm}")


def generate(rom, *, pcs=PCS, successors=SUCCESSORS, end=END,
             generator="tools/mk2/generate_video_irq.py"):
    if len(rom) != 0x100000 or hashlib.sha256(rom).hexdigest() != PROGRAM_SHA256:
        raise ValueError("MK2 video IRQ requires authenticated L3.1 program")
    output = [f"// Generated offline by {generator}; do not hand edit.",
              "// Authenticated L3.1 ROM SHA256: " + PROGRAM_SHA256,
              "// Constant reached-PC blocks only; no runtime opcode decoding."]
    from tools.mk2.offline_decode import decode
    rows, _ = decode(rom, pcs)
    qualified = set(pcs)
    for pc in pcs:
        size, flags, raw, asm = rows[pc]
        code = emit_instruction(pc, size, asm, raw, qualified, successors, end=end)
        output.extend([f"case 0x{pc:08x}u: {{ // {asm}", "    " + code, "    break;", "}"])
    return "\n".join(output) + "\n"


def load_program(directory):
    even, odd = ((directory / name).read_bytes() for name in PROGRAM_LANES)
    if len(even) != PROGRAM_LANE_BYTES or len(odd) != PROGRAM_LANE_BYTES:
        raise ValueError("MK2 program lane size changed")
    rom = bytearray(2 * PROGRAM_LANE_BYTES)
    rom[::2], rom[1::2] = even, odd
    return bytes(rom)



