"""Fixed ROM translation of the measured legal Coin 1 input queue continuation."""
from pathlib import Path
import json
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_task_batch as batch
from tools.mk2 import generate_video_irq as shared

START, END_PC, END = 3087189, 0xff8119b0, 3315882
REQUESTS = ((28, 1), (30, 0))
OUTPUT = __import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_coin_queue.inc'  # generated by the setup
PATH = Path(__file__).with_name('coin_queue_path.json')
measured = json.loads(PATH.read_text(encoding='utf8'))
PCS = tuple(sorted(set(batch.PCS) | {int(pc,16) for pc in measured['new_pcs']}))
SUCCESSORS = dict(batch.SUCCESSORS)
for source, targets in measured['successors'].items():
    pc = int(source,16)
    SUCCESSORS[pc] = tuple(sorted(set(SUCCESSORS.get(pc,())) | {int(p,16) for p in targets}))


def generate(rom):
    return shared.generate(rom, pcs=PCS, successors=SUCCESSORS, end=END_PC,
                           generator='tools/mk2/generate_coin_queue.py')


if __name__ == '__main__':
    OUTPUT.write_text(generate(shared.load_program(shared.ROOT/'roms/mk2')),encoding='utf8')
