"""Fixed ROM translation of the first original Coin1 task and legal release."""
from pathlib import Path
import json
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_coin_queue as coin
from tools.mk2 import generate_video_irq as shared

START,END_PC,END=3315882,0xff80dd30,3658091
OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_coin_accounting.inc'  # generated by the setup
PATH=Path(__file__).with_name('coin_accounting_path.json')
measured=json.loads(PATH.read_text(encoding='utf8'))
PCS=tuple(sorted(set(coin.PCS)|{int(pc,16) for pc in measured['new_pcs']}))
SUCCESSORS=dict(coin.SUCCESSORS)
for source,targets in measured['successors'].items():
    pc=int(source,16)
    SUCCESSORS[pc]=tuple(sorted(set(SUCCESSORS.get(pc,()))|{int(p,16) for p in targets}))


def generate(rom):
    return shared.generate(rom,pcs=PCS,successors=SUCCESSORS,end=END_PC,
                           generator='tools/mk2/generate_coin_accounting.py')


if __name__=='__main__':
    OUTPUT.write_text(generate(shared.load_program(shared.ROOT/'roms/mk2')),encoding='utf8')
