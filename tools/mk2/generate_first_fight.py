"""L3.1 measured first-fight blocks plus separately authenticated direct ROM CFG additions."""
from pathlib import Path
import json
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_selection as pair
from tools.mk2 import generate_video_irq as shared
from tools.mk2 import generate_static_cfg as static_cfg
from tools.mk2 import generate_valid_host_edges as valid_host_edges

START, END_PC, END = 30060282, 0xff80dd30, 150023965
OUTPUT = __import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_first_fight.inc'  # generated by the setup
PATH = Path(__file__).with_name('first_fight_path.json')
measured = json.loads(PATH.read_text(encoding='utf8'))
WINDOWS=tuple(measured['windows'])
if measured['start_cpu34_sha256']!=pair.measured['end_cpu34_sha256']:raise ValueError('First fight requires the original selection CPU34')
if len(WINDOWS)!=97: raise ValueError('First-fight scope requires ninety-seven measured intervals')
BOUNDS_OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_first_fight_bounds.inc'  # generated by the setup
HIGH_PUNCH_BOUNDS_OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_first_fight_high_punch_bounds.inc'  # generated by the setup


def interval(index):
    if type(index) is not int or not 0<=index<len(WINDOWS):
        raise ValueError('First-fight interval index must be an integer from0 through96')
    return WINDOWS[index]


def high_punch_interval():
    return measured['high_punch']


def generate_high_punch_bounds():
    w=high_punch_interval()
    return "// Generated expected-only high-punch CPU boundary; never imported into native state.\n{"+str(w['end'])+'ull,'+str(w['cpu_rows'])+'ull,"'+w['end_cpu34_sha256']+'"},\n'


def generate_bounds():
    rows=['// Generated expected-only CPU boundaries; never imported into native state.']
    for w in WINDOWS:
        rows.append('{'+str(w['end'])+'ull,'+str(w['cpu_rows'])+'ull,"'+w['end_cpu34_sha256']+'"},')
    return '\n'.join(rows)+'\n'

PCS = tuple(sorted(set(pair.PCS) | {int(pc, 16) for pc in measured['new_pcs']}))
SUCCESSORS = dict(pair.SUCCESSORS)
for source, targets in measured['successors'].items():
    pc = int(source, 16)
    SUCCESSORS[pc] = tuple(sorted(set(SUCCESSORS.get(pc, ())) | {int(p, 16) for p in targets}))

BASE_PCS, BASE_SUCCESSORS = PCS, SUCCESSORS
STATIC_CFG = static_cfg.load()
PCS, SUCCESSORS = static_cfg.extend(BASE_PCS, BASE_SUCCESSORS, STATIC_CFG)
STATIC_CFG_FRONTIERS = static_cfg.frontiers(STATIC_CFG)


def generate(rom):
    from tools.mk2.generate_architectural import generate as architectural
    outputs, _ = architectural(rom)
    return {path.name: text for path, text in outputs.items()}[OUTPUT.name]


if __name__ == '__main__':
    OUTPUT.write_text(generate(shared.load_program(shared.ROOT / 'roms/mk2')), encoding='utf8')
    BOUNDS_OUTPUT.write_text(generate_bounds(),encoding='utf8')
    HIGH_PUNCH_BOUNDS_OUTPUT.write_text(generate_high_punch_bounds(),encoding='utf8')
