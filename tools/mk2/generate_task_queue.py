def generate(rom):
    return shared.generate(rom, pcs=PCS, successors=SUCCESSORS, end=END,
                           generator="tools/mk2/generate_task_queue.py")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rom-directory", type=Path, default=ROOT / "roms/mk2")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = generate(shared.load_program(args.rom_directory))
    if args.check:
        if source != OUTPUT.read_text(encoding="utf-8"):
            raise SystemExit("MK2 task queue generated source is stale")
    else:
        OUTPUT.write_text(source, encoding="utf-8")
