"""Reproduce the authenticated fixed translation used by the finite valid-CMOS first draw."""
from pathlib import Path
import argparse
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_video_irq as shared
from tools.mk2 import generate_task_resume,generate_task_queue,generate_task_palette,generate_task_draw,generate_task_batch

OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_valid_cmos_draw.inc'  # generated by the setup
MODULES=(generate_task_resume,generate_task_queue,generate_task_palette,generate_task_draw,generate_task_batch)

def generate(rom):
    pcs=set();successors={}
    for module in MODULES:
        pcs.update(module.PCS)
        for pc,targets in module.SUCCESSORS.items():successors.setdefault(pc,set()).update(targets)
    shared.generate(rom,pcs=sorted(pcs),successors={pc:tuple(sorted(values))for pc,values in successors.items()},
                    end=0xff80dd30,generator='tools/mk2/generate_valid_cmos_draw.py')
    from tools.mk2.generate_architectural import generate as architectural
    return {path.name: text for path, text in architectural(rom)[0].items()}[OUTPUT.name]

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--roms',type=Path,default=shared.ROOT/'roms/mk2');parser.add_argument('--check',action='store_true')
    args=parser.parse_args();source=generate(shared.load_program(args.roms))
    if args.check:
        if source!=OUTPUT.read_text():raise SystemExit('valid-CMOS draw translation differs')
    else:OUTPUT.write_text(source,encoding='utf-8')
