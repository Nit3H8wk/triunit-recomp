"""Sparse authenticated original Start-release fixed blocks after the actual press."""
from pathlib import Path
import json
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[2]))
from tools.mk2 import generate_start_input as pair,generate_video_irq as shared

PATH=Path(__file__).with_name('start_release_path.json')
measured=json.loads(PATH.read_text(encoding='utf-8'))
START,END,END_PC=23108559,24004881,0xff80dd30
CPU_ROWS,PHYSICAL_ROWS=389582,727879
if (measured['start'],measured['end'],measured['cpu_rows'],measured['physical_rows'])!=(START,END,CPU_ROWS,PHYSICAL_ROWS):
    raise ValueError('Release manifest differs from the measured endpoint')
if measured['start_cpu34_sha256']!=pair.measured['end_cpu34_sha256']:
    raise ValueError('Release requires the complete measured Start CPU34 boundary')
OUTPUT=__import__('tools.setup.paths',fromlist=['output']).output('mk2')/'mk2_start_release.inc'  # generated by the setup
PCS=tuple(sorted(set(pair.PCS)|{int(pc,16) for pc in measured['new_pcs']}))
SUCCESSORS=dict(pair.SUCCESSORS)
for source,targets in measured['successors'].items():
    pc=int(source,16)
    SUCCESSORS[pc]=tuple(sorted(set(SUCCESSORS.get(pc,()))|{int(p,16) for p in targets}))


def generate(rom):
    pair.generate(rom)
    from tools.mk2.offline_decode import decode
    rows,_=decode(rom,PCS)
    previous=set(pair.PCS);qualified=set(PCS)
    output=['// Generated offline by tools/mk2/generate_start_release.py; do not hand edit.',
            '// Authenticated L3.1 ROM SHA256: '+shared.PROGRAM_SHA256,
            '// Only measured changed/new blocks; all others retain the original Start translation.']
    for pc in PCS:
        size,flags,raw,asm=rows[pc]
        code=shared.emit_instruction(pc,size,asm,raw,qualified,SUCCESSORS,end=END_PC)
        if pc in previous and code==shared.emit_instruction(pc,size,asm,raw,previous,pair.SUCCESSORS,end=END_PC):continue
        output.extend([f'case 0x{pc:08x}u: {{ // {asm}','    '+code,'    break;','}'])
    return '\n'.join(output)+'\n'


if __name__=='__main__':OUTPUT.write_text(generate(shared.load_program(shared.ROOT/'roms/mk2')),encoding='utf-8')
