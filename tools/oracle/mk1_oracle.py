DSW=0xfeff                 # the cabinet of every MK1 consumer (coinage from the switches)
MAME_DSW_DEFAULT=0xfe7d    # midtunit.cpp INPUT_PORTS( mk ) DSW defaults; the fields that differ go to cfg/mk.cfg
DSW_FIELDS=(0x1,0x2,0x7c,0x80,0x100,0x200,0x400,0x800,0x1000,0x2000,0x4000,0x8000)
TASK_ENTRY=0xffc8bf50      # first task entry of the power-on (stop of Mk5TaskBodyRunner::Boot)

def mame_mk(temp,nvram,seconds,script=None):
    """MAME 0.280 `mk` in `temp`: DSW by cfg, nvram/mk/nvram from `nvram` (None: MAME's default, every word 0), no video
    or sound output. Returns (command result, saved nvram bytes or None, debugger log text, ROM identity)."""
    from tools.oracle import mame_step
    if q.sha(mame_step.CORE)!=mame_step.CORE_SHA:raise ValueError('Reference core identity changed')
    rompath,identity=mame_rompath(temp)
    if nvram is not None:(temp/'nvram/mk').mkdir(parents=True);(temp/'nvram/mk/nvram').write_bytes(nvram)
    (temp/'cfg').mkdir()
    fields=''.join(f'<port tag=":DSW" type="DIPSWITCH" mask="{m}" defvalue="{MAME_DSW_DEFAULT&m}" value="{DSW&m}" />' for m in DSW_FIELDS if (DSW^MAME_DSW_DEFAULT)&m)
    (temp/'cfg/mk.cfg').write_text('<?xml version="1.0"?><mameconfig version="10"><system name="mk"><input>'+fields+'</input></system></mameconfig>',encoding='ascii')
    debug=[]
    if script:(temp/'probe.cmd').write_text(script,encoding='ascii');debug=['-debug','-debugger','windows','-debuglog','-debugscript','probe.cmd']
    r=q.command([mame_step.CORE,'mk','-rompath',rompath,'-noreadconfig','-skip_gameinfo','-noplugins','-video','none','-sound','none','-nothrottle',*debug,
                 '-nvram_directory','nvram','-cfg_directory','cfg','-homepath','home','-snapshot_directory','snap','-seconds_to_run',str(seconds)],temp,cwd=temp,timeout=900)
    saved=(temp/'nvram/mk/nvram').read_bytes() if (temp/'nvram/mk/nvram').is_file() else None
    log=(temp/'debug.log').read_text('utf-8',errors='replace') if (temp/'debug.log').is_file() else ''
    return r,saved,log,identity

def native_task_entry(exe,image,scratch):
    """Product CLI power-on (boot-flow stage) from `image`: stop, PC, ST, cycles and A0-A14 at the first task entry."""
    path=scratch/'power-on-cmos.bin';path.write_bytes(image)
    args=[exe,'--roms',ROOT/'roms','--stage','boot-flow','--cmos-input',path,'--irq-pending','0x400','--raster-next-line','1','--raster-quanta','6325']
    for prefix in ('','boot-','task-'):args+=[f'--{prefix}dsw-word',str(DSW)]
    r=q.command(args,scratch,cwd=ROOT,env=dict(PATH=str(q.DEFAULT_CC.parent),MK1_MUSIC_MODE='original',MK1_GAME_VOLUME='0'),timeout=120,output_limit=256*1024)
    row=next((json.loads(l) for l in r['stdout'].splitlines() if l.startswith('{') and '"scope"' in l),None) or {}
    return dict(stop=row.get('stop'),pc=row.get('next_original_pc'),st=row.get('status'),cycles=row.get('reference_model_cycles'),a=(row.get('a') or [])[:15])

