def plan(forms_filter=None):
    """Sites per (graph, form); chosen sites, device and excluded sites listed apart."""
    rows={}
    for graph,path in GRAPHS.items():
        for pc,(asm,n,body) in read_graph(path).items():
            rows.setdefault((graph,form(asm)),[]).append((graph,pc,asm,n,body))
    out={}
    for (graph,f),sites in sorted(rows.items()):
        if forms_filter and f not in forms_filter:continue
        entry=dict(graph=graph,form=f,sites=len(sites),device=[],excluded=[],chosen=[])
        testable=[]
        for s in sites:
            why=HOST_ENTRIES.get((graph,s[1])) or ('emitter rejection (throw Untranslated)' if 'throw TaskBodyStop::Untranslated;' in s[4] else None)
            if why:entry['excluded'].append(dict(pc=f'{s[1]:08x}',asm=s[2],reason=why));continue
            d=device(s[2])
            if d:entry['device'].append(dict(pc=f'{s[1]:08x}',asm=s[2],reason=d));continue
            testable.append(s)
        entry['chosen']=choose(testable)
        out[(graph,f)]=entry
    return out

def mame_rompath(scratch):
    """MAME 0.280 names the mk set differently from roms/mk; zip the local files under the driver's names by CRC
    (as tools/audio_reference_20261024/capture_reference.py). The zip lives in the caller's scratch tree only."""
    import hashlib,zipfile,zlib
    section=(ROOT/'docs/investigation/sources/midtunit.cpp').read_text().split('ROM_START( mk )',1)[1].split('ROM_END',1)[0]
    by_crc={zlib.crc32(p.read_bytes()):p for p in (ROOT/'roms/mk1').iterdir() if p.is_file()}
    (scratch/'mame-roms').mkdir();identity={}
    with zipfile.ZipFile(scratch/'mame-roms/mk.zip','w',zipfile.ZIP_STORED) as z:
        for name,crc in re.findall(r'ROM_LOAD(?:16_BYTE|32_BYTE)?\(\s*"([^"]+)".*?CRC\(([0-9a-f]+)\)',section):
            data=by_crc[int(crc,16)].read_bytes();z.writestr(name,data)
            identity[name]=dict(file=by_crc[int(crc,16)].name,crc32=crc,sha256=hashlib.sha256(data).hexdigest())
    return scratch/'mame-roms',identity

