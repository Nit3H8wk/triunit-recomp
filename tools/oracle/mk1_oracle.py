def seed_check(images=None):
    """The setup seed against the Original in the pinned MAME, same cabinet (DSW FEFFh):
    factory   MAME from its default NVRAM (every word 0) saves, after the factory restore, the setup seed byte for byte;
    power_on  MAME with the seed as nvram and the product engine from the same image reach the first task entry with the
              same PC, ST, cycle count and A0-A14. `images` {label: path} adds the power-on check for other CMOS images."""
    import hashlib
    image=seed().read_bytes();engine=engine_path()
    rec=dict(schema='mk1-seed-oracle/1',seed_sha256=q.sha(seed()),dsw=f'{DSW:04x}',engine_sha256=q.sha(engine),passed=False,power_on={})
    regs=[f'a{i}' for i in range(15)]
    fmt='MK1_TASK '+' '.join(['%X']*18)+'\\n'
    script=f'focus :maincpu\nbpset {TASK_ENTRY:x},1,{{printf "{fmt}",pc,st,totalcycles,'+','.join(regs)+';quit}\ngo\n'
    with q.scratch_tree() as (scratch,cleanup):
        (scratch/'factory').mkdir();r,saved,_,identity=mame_mk(scratch/'factory',None,10)
        rec['mame_roms']=identity
        rec['factory']=dict(mame_passed=r['passed'],mame_seconds=r.get('wall_seconds'),saved_sha256=hashlib.sha256(saved).hexdigest() if saved else None,
                            bytes=len(saved or b''),equal=saved==image,differing_bytes=None if saved is None else sum(1 for x,y in zip(saved,image) if x!=y))
        for label,data in {'seed':image,**{k:Path(v).read_bytes() for k,v in (images or {}).items()}}.items():
            (scratch/label).mkdir();r,_,log,_=mame_mk(scratch/label,data,30,script)
            rows=[l.split()[1:] for l in log.splitlines() if l.startswith('MK1_TASK ')]
            mame=dict(pc=int(rows[0][0],16),st=int(rows[0][1],16),cycles=int(rows[0][2],16),a=[int(x,16) for x in rows[0][3:18]]) if len(rows)==1 else None
            nat=native_task_entry(engine,data,scratch/label)
            rec['power_on'][label]=dict(cmos_sha256=hashlib.sha256(data).hexdigest(),mame=mame,native=nat,mame_passed=r['passed'],
                                        equal=bool(mame) and nat['stop']=='task-body-untranslated' and all(mame[k]==nat[k] for k in ('pc','st','cycles','a')))
    rec['cleanup']=cleanup
    rec['passed']=rec['factory']['equal'] and all(x['equal'] for x in rec['power_on'].values()) and cleanup.get('exists_after') is False
    return rec

