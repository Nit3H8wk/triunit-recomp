def read_graph(path):
    """{pc: (asm, next, body lines)} from the emitted labels, as the inventory reads them."""
    lines=path.read_text('utf-8').split('\n');sites={}
    for i,l in enumerate(lines):
        m=LABEL.match(l)
        if not m:continue
        body=[];j=i+1
        while lines[j]!='}':body.append(lines[j]);j+=1
        n=int(re.search(r'instruction_next=0x([0-9a-f]{8})',next(b for b in body if b.startswith('pre('))).group(1),16)
        sites[int(m.group(1),16)]=(m.group(2),n,body)
    return sites

