def form(asm):
    op,*rest=asm.split(None,1)
    shape=re.sub(r'\b[0-9A-F]+h\b','K',re.sub(r'\b(?:[AB](?:1[0-5]|[0-9])|SP)\b','R',rest[0])) if rest else ''
