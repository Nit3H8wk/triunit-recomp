#!/usr/bin/env python3
# Unit tests of the publication guard. Every sample is synthetic and is written
# to a throw-away git repository under the system temp directory.
import base64
import contextlib
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import audit  # noqa: E402
import install_hooks  # noqa: E402

for _k in [k for k in os.environ if k.startswith("GIT_")]:
    del os.environ[_k]   # never let a hook's GIT_DIR/GIT_INDEX_FILE leak into the temp repositories

CFG = audit.load_config(audit.DEFAULT_CONFIG)


def sh(root, *args):
    subprocess.run(["git", "-C", str(root), "-c", "user.name=t", "-c", "user.email=t@example.invalid",
                    "-c", "core.autocrlf=false", "-c", "commit.gpgsign=false"] + list(args),
                   check=True, capture_output=True)


class Repo:
    def __init__(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="audit-test-")
        self.root = Path(self.tmp.name)
        sh(self.root, "init", "-q")

    def write(self, path, data, add=True):
        full = self.root / path
        full.parent.mkdir(parents=True, exist_ok=True)
        full.write_bytes(data if isinstance(data, bytes) else data.encode("utf-8"))
        if add:
            sh(self.root, "add", "--", path)

    def audit(self, *flags):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = audit.main(["--json", "--root", str(self.root)] + list(flags))
        return code, json.loads(out.getvalue())

    def close(self):
        self.tmp.cleanup()


def rules(report, path=None):
    return sorted({f["rule"] for f in report["findings"] if path is None or f["path"].split("@")[0] == path})


def pcs(count):
    return "\n".join("    0x%08x," % (0xff800000 + 0x10 * i) for i in range(count)) + "\n"


class RuleTests(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()

    def tearDown(self):
        self.repo.close()

    def check(self, path, data, expected):
        self.repo.write(path, data)
        code, report = self.repo.audit()
        self.assertEqual(rules(report, path), expected, report["findings"])
        self.assertEqual(code, 1 if expected else 0)
        return report

    def test_forbidden_extension(self):
        self.check("media/title.png", "not really an image", ["forbidden-extension"])
        self.check("dump/prog.u12", "x", ["forbidden-extension"])
        self.check("evidence/listing.tsv", "a\tb\n", ["forbidden-extension"])
        self.check("gen/table.inc", "int x;\n", ["forbidden-extension"])

    def test_forbidden_extension_negative(self):
        self.check("src/ok.cpp", "int main() { return 0; }\n", [])
        self.check("native/launcher/native_roms.inc", '{"a.bin",16,"' + "0" * 64 + '"},\n', [])

    def test_binary(self):
        self.check("data/blob.dat", bytes(range(256)) * 4, ["binary"])

    def test_binary_negative(self):
        self.check("notes/texto.txt", "Configuração do áudio: volume, saída e latência.\n", [])

    def test_generated_header(self):
        self.check("src/out.cpp", "// Generated by tools/x.py\nint a;\n", ["generated-header"])
        self.check("src/out2.hpp", "#pragma once\n/* " + "AUTO-" + "GENERATED */\n", ["generated-header"])

    def test_generated_header_negative(self):
        self.check("tools/gen.py", '"""Writer."""\nimport os\n# generated by the setup into generated/\n', [])
        self.check("src/late.cpp", "int a;\n" * 25 + "// Generated by nothing\n", [])

    def test_disassembly_address(self):
        self.check("src/a.cpp", "int a; // FF812340: MOVI 10h,A0\n", ["disassembly"])
        self.check("src/b.py", "x = 1  # 0xff812340 jruc 0xff812400\n", ["disassembly"])
        self.check("notes/c.md", "```\n0123: AR = AX0 + AY0\n```\n", ["disassembly"])
        self.check("tools/d.lua", "-- F01C: LDA #$10\n", ["disassembly"])

    def test_disassembly_listing(self):
        self.check("src/e.cpp", "// MOVE A0,A1\n// ADDK 1,A1\nint e;\n", ["disassembly"])
        self.check("src/f.cpp", "/*\n  AR = AX0 + AY0\n  DM(I0,M1) = AR\n*/\n", ["disassembly"])

    def test_disassembly_negative(self):
        text = ("// MOVI IW,Rd loads the immediate; MOVE Rs,Rd copies a register.\n"
                "// The JRUC form branches; CALLA pushes the PC.\n"
                "const char* s = \"// FF812340: MOVI 10h,A0\";\n"
                "// at 15/11/2026: SRL count fixed\n"
                "// MOVE A0,A1 single listing line\n")
        self.check("native/core.cpp", text, [])

    def test_excerpt_hides_long_hex(self):
        report = self.check("src/g.cpp", "// FF812340: MOVI 0x0123456789abcdef0123,A0\n", ["disassembly"])
        ex = report["findings"][0]["excerpt"]
        self.assertNotRegex(ex, "[0-9A-Fa-f]{17}")
        self.assertLessEqual(len(ex), audit.EXCERPT_MAX)

    def test_pc_density(self):
        self.check("native/tbl.cpp", "int t[] = {\n" + pcs(31) + "};\n", ["pc-density"])

    def test_pc_density_negative(self):
        self.check("native/tbl.cpp", "int t[] = {\n" + pcs(30) + "};\n", [])
        self.check("docs/tbl.md", pcs(40).replace(",", " is out of scope"), [])

    def test_hex_run(self):
        self.check("src/h.txt", "blob=" + "a1" * 48 + "\n", ["hex-run"])
        lits = ", ".join("0x%02x" % i for i in range(32))
        self.check("src/i.cpp", "uint8_t d[] = {" + lits + "};\n", ["hex-run"])
        nested = ",\n".join("{0x%x, 0x%x}" % (i, i + 1) for i in range(16))
        self.check("src/j.cpp", "Pair p[] = {" + nested + "};\n", ["hex-run"])

    def test_hex_run_negative(self):
        text = "sha256 " + "ab" * 32 + "\ncommit " + "cd" * 20 + "\n"
        text += "uint8_t d[] = {" + ", ".join("0x%02x" % i for i in range(31)) + "};\n"
        self.check("src/k.cpp", text, [])

    def test_base64_run(self):
        blob = base64.b64encode(bytes((i * 37 + 11) % 256 for i in range(90))).decode()
        self.assertEqual(len(blob), 120)
        self.check("src/l.txt", "payload: " + blob + "\n", ["base64-run"])

    def test_base64_run_negative(self):
        blob = base64.b64encode(bytes((i * 37 + 11) % 256 for i in range(87))).decode()[:119]
        self.check("src/m.txt", "payload: " + blob + "\n", [])

    def test_mark_term(self):
        self.check("src/n.cpp", "// Scorpion palette swap\n", ["mark-term"])
        self.check("src/o.cpp", "int sub_zero_state;\n", ["mark-term"])
        self.check("src/p.md", "Smoke appears in the third game.\n", ["mark-term"])

    def test_mark_term_negative(self):
        self.check("README.md", "Compatibility: Scorpion edition.\n", [])
        self.check("src/q.py", "def smoke(frames):  # smoke test of the midway point\n", [])
        report = self.check("src/mk2_scorpion.cpp", "int mk5_boot;\n", [])
        self.assertEqual(report["info"]["paths_with_mark_terms"], 1)


class ModeTests(unittest.TestCase):
    def setUp(self):
        self.repo = Repo()

    def tearDown(self):
        self.repo.close()

    def test_clean_tree_exit_zero(self):
        self.repo.write("src/ok.cpp", "int ok;\n")
        code, report = self.repo.audit()
        self.assertEqual((code, report["finding_count"], report["files_scanned"]), (0, 0, 1))

    def test_staged_reads_the_index(self):
        self.repo.write("src/a.cpp", "// FF812340: MOVI 10h,A0\n")
        self.repo.write("src/a.cpp", "int clean;\n", add=False)   # working tree differs from the index
        code, report = self.repo.audit("--staged")
        self.assertEqual((code, rules(report)), (1, ["disassembly"]))
        code, report = self.repo.audit()
        self.assertEqual((code, report["finding_count"]), (0, 0))

    def test_staged_only_changed_files(self):
        self.repo.write("src/old.cpp", "// Scorpion\n")
        sh(self.repo.root, "commit", "-q", "-m", "seed")
        self.repo.write("src/new.cpp", "int fine;\n")
        code, report = self.repo.audit("--staged")
        self.assertEqual((code, report["files_scanned"]), (0, 1))

    def test_all_objects_sees_history(self):
        self.repo.write("media/a.png", "x")
        self.repo.write("src/b.cpp", "// Scorpion\n")
        sh(self.repo.root, "commit", "-q", "-m", "one")
        sh(self.repo.root, "rm", "-q", "media/a.png", "src/b.cpp")
        self.repo.write("src/c.cpp", "int c;\n")
        sh(self.repo.root, "commit", "-q", "-m", "two")
        self.assertEqual(self.repo.audit()[0], 0)
        code, report = self.repo.audit("--all-objects")
        self.assertEqual((code, rules(report)), (1, ["forbidden-extension", "mark-term"]))

    def test_bad_config_exit_two(self):
        bad = self.repo.root / "bad.json"
        bad.write_text("{}", encoding="utf-8")
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(audit.main(["--root", str(self.repo.root), "--config", str(bad)]), 2)


class HookTests(unittest.TestCase):
    def test_install_idempotent_foreign_uninstall(self):
        repo = Repo()
        try:
            hook = install_hooks.hooks_dir(repo.root) / "pre-commit"
            args = ["--repo", str(repo.root)]
            with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                self.assertEqual(install_hooks.main(args), 0)
                self.assertIn("audit.py\" --staged", hook.read_text(encoding="utf-8"))
                self.assertEqual(install_hooks.main(args), 0)
                hook.write_text("#!/bin/sh\necho mine\n", encoding="utf-8")
                self.assertEqual(install_hooks.main(args), 1)
                self.assertEqual(install_hooks.main(args + ["--uninstall"]), 1)
                self.assertEqual(install_hooks.main(args + ["--force"]), 0)
                self.assertTrue(hook.with_name("pre-commit.foreign").exists())
                self.assertEqual(install_hooks.main(args + ["--uninstall"]), 0)
                self.assertFalse(hook.exists())
        finally:
            repo.close()


if __name__ == "__main__":
    unittest.main()
